"""Shared helpers for profiling reports: DuckDB views over data/interim/ and markdown output."""

import json
import logging
from pathlib import Path

import duckdb

logger = logging.getLogger(__name__)

INTERIM_DIR = Path("data/interim")
REPORT_DIR = Path("docs/profiling")

Sections = list[tuple[str, str]]


def connect(interim_dir: Path = INTERIM_DIR) -> duckdb.DuckDBPyConnection:
    """In-memory DuckDB: views `bulk`, `narratives` (raw archive rows), `archive`, `narrative`."""
    if not (interim_dir / "INTERIM.json").is_file():
        raise FileNotFoundError(f"{interim_dir}/INTERIM.json missing; run profiling.interim")
    con = duckdb.connect()
    for name in ("bulk", "narratives"):
        glob = str(interim_dir / name / "*.parquet").replace("'", "''")
        con.execute(f"CREATE VIEW {name} AS SELECT * FROM read_parquet('{glob}')")
    # One archive row per complaint (an id can appear in several archive files); deterministic.
    con.execute(
        """CREATE VIEW archive AS SELECT * FROM narratives
           QUALIFY row_number() OVER (PARTITION BY "Complaint ID" ORDER BY source_file) = 1"""
    )
    # Non-empty narratives, one per complaint.
    con.execute(
        """CREATE VIEW narrative AS
           SELECT "Complaint ID" AS complaint_id, "Consumer complaint narrative" AS txt
           FROM archive WHERE trim("Consumer complaint narrative") <> ''"""
    )
    return con


def _cell(value: object) -> str:
    if value is None:
        return "∅"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        return f"{value:,.2f}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def md_table(con: duckdb.DuckDBPyConnection, sql: str) -> str:
    cur = con.execute(sql)
    header = [d[0] for d in cur.description]
    rows = cur.fetchall()
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
        *("| " + " | ".join(_cell(v) for v in row) + " |" for row in rows),
    ]
    return "\n".join(lines)


def snapshot_line(interim_dir: Path = INTERIM_DIR) -> str:
    info = json.loads((interim_dir / "INTERIM.json").read_text())
    bulk = info["bulk"]["sources"][0]
    return (
        f"Snapshot: `{bulk['path']}` (retrieved {bulk['retrieved_at']}, "
        f"sha256 `{bulk['sha256'][:12]}…`); {len(info['narratives']['sources'])} narrative "
        f"archive files; interim built {info['built_at']}."
    )


def write_report(
    path: Path, title: str, module: str, sections: Sections, interim_dir: Path = INTERIM_DIR
) -> None:
    parts = [
        f"# {title}",
        "",
        snapshot_line(interim_dir),
        f"Generated by `uv run python -m {module}`. Empty CSV fields are read as NULL (∅).",
    ]
    for heading, body in sections:
        parts += ["", f"## {heading}", "", body]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts) + "\n")
    logger.info("wrote %s", path)
