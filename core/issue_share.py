"""Generate the credit card issue-share metrics (M3 decision): one governed ratio per issue,
because a single ratio grouped by issue would make every share 100%. Denominator: credit
card complaints with a known issue.

Measures go into the `complaints` semantic model (between the GENERATED markers in
complaints.yml), so issue shares reach every dimension the other metrics do (review 4 #2);
metrics go in issue_share.yml. Canonical issues come from seed credit_card_issue_map; tests
fail if either is stale.
Run: uv run python -m core.issue_share
"""

import csv
import logging
import re

from core.log import configure_logging
from core.warehouse import DBT_DIR

logger = logging.getLogger(__name__)

SEED = DBT_DIR / "seeds" / "credit_card_issue_map.csv"
COMPLAINTS_YML = DBT_DIR / "semantic_models" / "complaints.yml"
OUT = DBT_DIR / "semantic_models" / "issue_share.yml"
BEGIN = "      # BEGIN GENERATED credit card issue measures (uv run python -m core.issue_share)\n"
END = "      # END GENERATED credit card issue measures\n"


def slug(issue: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", issue.lower()).strip("_")


def canonical_issues() -> list[str]:
    with SEED.open(newline="") as f:
        return sorted({row["canonical_issue"] for row in csv.DictReader(f)})


def render_measures() -> str:
    lines = [
        "      - name: credit_card_issue_known_complaints",
        "        description: Credit card complaints with a known issue (null issue excluded).",
        "        agg: sum",
        '        expr: "case when credit_card_issue is not null then 1 else 0 end"',
    ]
    for issue in canonical_issues():
        literal = issue.replace("'", "''")
        lines += [
            f"      - name: cc_issue_{slug(issue)}",
            "        agg: sum",
            f"        expr: \"case when credit_card_issue = '{literal}' then 1 else 0 end\"",
        ]
    return "\n".join(lines) + "\n"


def render_complaints_yml(current: str) -> str:
    head, rest = current.split(BEGIN)
    _, tail = rest.split(END)
    return head + BEGIN + render_measures() + END + tail


def render() -> str:
    lines = [
        "# GENERATED by `uv run python -m core.issue_share` from seeds/credit_card_issue_map.csv.",
        "# Do not edit by hand; tests/test_issue_share.py fails if this file is stale.",
        "# Measures live in the complaints semantic model (complaints.yml, GENERATED section).",
        "metrics:",
        "  - name: credit_card_issue_known_count",
        "    label: Credit card complaints with a known issue",
        "    type: simple",
        "    type_params: {measure: credit_card_issue_known_complaints}",
    ]
    for issue in canonical_issues():
        s = slug(issue)
        label = issue.replace('"', "'")
        lines += [
            f"  - name: issue_count_{s}",
            f'    label: "Credit card complaints: {label}"',
            "    type: simple",
            f"    type_params: {{measure: cc_issue_{s}}}",
            f"  - name: issue_share_{s}",
            f'    label: "Issue share: {label}"',
            "    description: >-",
            f"      Credit card complaints with issue '{label}' / credit card complaints with a",
            "      known issue (all eras mapped to the current list; null issue excluded).",
            "    type: ratio",
            "    type_params:",
            f"      numerator: issue_count_{s}",
            "      denominator: credit_card_issue_known_count",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    configure_logging()
    COMPLAINTS_YML.write_text(render_complaints_yml(COMPLAINTS_YML.read_text()))
    OUT.write_text(render())
    logger.info("wrote %s and %s (%d issues)", COMPLAINTS_YML, OUT, len(canonical_issues()))


if __name__ == "__main__":
    main()
